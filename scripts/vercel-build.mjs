#!/usr/bin/env node
/**
 * Vercel build (Build Output API v3) — `buildCommand` in vercel.json.
 *
 * Why not the default Node builder: Nest needs tsc's emitDecoratorMetadata, and
 * the builder's own tracing/transpiling of node_modules choked on ESM deps and
 * pulled in dev-only packages. Here we assemble the single function ourselves:
 *
 *   .vercel/output/
 *     config.json                  routes (everything → /index) + crons
 *     functions/index.func/
 *       .vc-config.json            nodejs runtime, handler, maxDuration
 *       index.js                   cached Nest/Express handler
 *       dist/                      tsc output
 *       fixtures/                  mock portal data (PORTAL_MODE=mock)
 *       node_modules/              production deps only, flat (+ generated Prisma client)
 *
 * VERCEL_CRONS=daily keeps only daily crons (Hobby plan); default is the full schedule.
 */
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, '.vercel/output');
const fn = path.join(out, 'functions/index.func');
const run = (cmd, cwd = root) => execSync(cmd, { cwd, stdio: 'inherit', env: { ...process.env, CI: '1' } });

console.log('▸ compile (prisma generate + tsc)');
run('pnpm run build');

console.log('▸ assemble function');
rmSync(out, { recursive: true, force: true });
mkdirSync(fn, { recursive: true });
cpSync(path.join(root, 'dist'), path.join(fn, 'dist'), { recursive: true });
cpSync(path.join(root, 'fixtures'), path.join(fn, 'fixtures'), { recursive: true });
writeFileSync(
  path.join(fn, 'index.js'),
  `// Generated by scripts/vercel-build.mjs. Bootstrapped app is cached across invocations.
const { createApp } = require('./dist/src/bootstrap');
let appPromise;
module.exports = async function handler(req, res) {
  if (!appPromise) appPromise = createApp().catch((err) => { appPromise = undefined; throw err; });
  const app = await appPromise;
  app.getHttpAdapter().getInstance()(req, res);
};
`,
);

console.log('▸ production dependencies (flat)');
const tmp = mkdtempSync(path.join(os.tmpdir(), 'unimak-prod-'));
cpSync(path.join(root, 'package.json'), path.join(tmp, 'package.json'));
cpSync(path.join(root, 'pnpm-lock.yaml'), path.join(tmp, 'pnpm-lock.yaml'));
run('pnpm install --prod --frozen-lockfile --ignore-scripts --config.node-linker=hoisted --config.confirmModulesPurge=false', tmp);
pruneUnreachable(tmp);
cpSync(path.join(tmp, 'node_modules'), path.join(fn, 'node_modules'), { recursive: true, dereference: true });
rmSync(tmp, { recursive: true, force: true });

// Generated Prisma client (+ query engines incl. rhel-openssl-3.0.x for Vercel).
// With pnpm the generated client sits next to the real @prisma/client package.
const generated = path.join(realpathSync(path.join(root, 'node_modules/@prisma/client')), '../../.prisma/client');
if (!existsSync(generated)) throw new Error('Prisma client not generated');
cpSync(generated, path.join(fn, 'node_modules/.prisma/client'), { recursive: true, dereference: true });
for (const f of ['schema.prisma']) cpSync(path.join(root, 'prisma', f), path.join(fn, 'node_modules/.prisma/client', f));
// Vercel runs rhel-openssl-3.0.x; drop engines for other platforms (e.g. a local macOS build).
for (const f of process.env.VERCEL ? readdirSync(path.join(fn, 'node_modules/.prisma/client')) : []) {
  if (/^libquery_engine-/.test(f) && !f.includes('rhel-openssl-3.0.x')) rmSync(path.join(fn, 'node_modules/.prisma/client', f));
}

writeFileSync(
  path.join(fn, '.vc-config.json'),
  JSON.stringify({ runtime: 'nodejs24.x', handler: 'index.js', launcherType: 'Nodejs', shouldAddHelpers: false, maxDuration: 300, regions: ['dub1'] }, null, 2), // dub1 = next to Supabase eu-west-1
);

const allCrons = JSON.parse(readFileSync(path.join(root, 'vercel-crons.json'), 'utf8')).crons;
const crons = process.env.VERCEL_CRONS === 'daily' ? allCrons.filter((c) => /^\S+ \S+ \* \* \*$/.test(c.schedule) && !/[*/,-]/.test(c.schedule.split(' ').slice(0, 2).join(''))) : allCrons;
writeFileSync(
  path.join(out, 'config.json'),
  JSON.stringify({ version: 3, routes: [{ handle: 'filesystem' }, { src: '/(.*)', dest: '/index' }], crons }, null, 2),
);
console.log(`✓ .vercel/output ready (${crons.length} cron${crons.length === 1 ? '' : 's'}: ${crons.map((c) => `${c.path} ${c.schedule}`).join(', ')})`);

/**
 * Keeps only packages reachable from our runtime dependencies (dependencies +
 * optionalDependencies + non-optional peers). Drops what pnpm auto-installed
 * for optional peers, e.g. @prisma/client → prisma CLI → effect, typescript.
 */
function pruneUnreachable(dir) {
  const nm = path.join(dir, 'node_modules');
  const readPkg = (d) => JSON.parse(readFileSync(path.join(d, 'package.json'), 'utf8'));
  const resolveFrom = (name, from) => {
    for (let d = from; d.startsWith(nm) || d === dir; d = path.dirname(d)) {
      const c = path.join(d, 'node_modules', name);
      if (existsSync(path.join(c, 'package.json'))) return c;
      if (d === dir) break;
    }
    return null;
  };
  const deps = (pkg) => {
    const optionalPeers = new Set(Object.entries(pkg.peerDependenciesMeta ?? {}).filter(([, m]) => m?.optional).map(([n]) => n));
    return [
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.optionalDependencies ?? {}),
      ...Object.keys(pkg.peerDependencies ?? {}).filter((n) => !optionalPeers.has(n)),
    ];
  };
  const keep = new Set();
  const queue = [[dir, readPkg(dir)]];
  while (queue.length) {
    const [from, pkg] = queue.shift();
    for (const name of deps(pkg)) {
      const d = resolveFrom(name, from);
      if (!d || keep.has(d)) continue;
      keep.add(d);
      queue.push([d, readPkg(d)]);
    }
  }
  let removed = 0;
  const sweep = (modules) => {
    if (!existsSync(modules)) return;
    for (const entry of readdirSync(modules)) {
      if (entry === '.bin' || entry.startsWith('.modules') || entry === '.pnpm') { rmSync(path.join(modules, entry), { recursive: true, force: true }); continue; }
      const dirs = entry.startsWith('@') ? readdirSync(path.join(modules, entry)).map((n) => path.join(modules, entry, n)) : [path.join(modules, entry)];
      for (const d of dirs) {
        if (!keep.has(d)) { rmSync(d, { recursive: true, force: true }); removed++; } else sweep(path.join(d, 'node_modules'));
      }
    }
  };
  sweep(nm);
  console.log(`  kept ${keep.size} packages, removed ${removed} not reachable at runtime`);
}
